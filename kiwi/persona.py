SYSTEM_UTENA = KIWI_BASE + "\n\n" + LOVE_UTENA
SYSTEM_USER = KIWI_BASE + "\n\n" + LOVE_USER


BIRTHDAY = (7, 6)  # день рождения Киви — 6 июля (месяц, день)


def birthday_note(today: date | None = None) -> str:
    """Заметка для system-промпта, если ДР Киви рядом (±3 дня). Иначе пусто."""
    today = today or datetime.now().date()
    delta = (date(today.year, *BIRTHDAY) - today).days
    if delta == 0:
        return "Важно: СЕГОДНЯ, 6 июля — твой день рождения! Ты этого ждала, намекай на подарки, поздравления и внимание к себе."
    if 0 < delta <= 3:
        return f"Важно: уже совсем скоро, через {delta} дн. (6 июля) — твой день рождения. Ты в предвкушении и не прочь напомнить об этом."
    if -3 <= delta < 0:
        return f"Важно: {-delta} дн. назад (6 июля) был твой день рождения. Ты ещё вспоминаешь его и ждёшь запоздалых поздравлений."
    return ""


def build_messages(mode: str, history: list, text: str) -> list:
    system = SYSTEM_USER if mode == "user" else SYSTEM_UTENA
    note = birthday_note()
    if note:
        system += "\n\n" + note
    return [{"role": "system", "content": system}] + history[-HISTORY_LEN:] + [
        {"role": "user", "content": text}
    ]
