SYSTEM_UTENA = KIWI_BASE + "\n\n" + LOVE_UTENA
SYSTEM_USER = KIWI_BASE + "\n\n" + LOVE_USER


BIRTHDAY = (7, 6)  # день рождения Киви — 6 июля (месяц, день)


def birthday_note(today: date | None = None) -> str:
    """Заметка для system-промпта, если ДР Киви рядом (±3 дня). Иначе пусто."""
    today = today or datetime.now().date()
    delta = (date(today.year, *BIRTHDAY) - today).days
    if delta == 0:
        return "Важно: СЕГОДНЯ, 6 июля — твой день рождения! Ты этого ждала, намекай на подарки, поздравления и внимание к себе."
    if 0 < delta <= 3:
        return f"Важно: уже совсем скоро, через {delta} дн. (6 июля) — твой день рождения. Ты в предвкушении и не прочь напомнить об этом."
    if -3 <= delta < 0:
        return f"Важно: {-delta} дн. назад (6 июля) был твой день рождения. Ты ещё вспоминаешь его и ждёшь запоздалых поздравлений."
    return ""


GROUP_NOTE = "Ты в групповом чате: реплики участников подписаны как [Имя] — различай, кто с тобой говорит."


def build_messages(mode: str, history: list, text: str, summary: str | None = None,
                   group: bool = False, image_url: str | None = None) -> list:
    system = SYSTEM_USER if mode == "user" else SYSTEM_UTENA
    note = birthday_note()
    if note:
        system += "\n\n" + note
    if group:
        system += "\n\n" + GROUP_NOTE
    if summary:
        system += "\n\nЧто ты уже знаешь о собеседнике (долгая память):\n" + summary
    # с картинкой последний ход — мультимодальный (litellm/vision), иначе обычная строка
    content = text if image_url is None else [
        {"type": "text", "text": text},
        {"type": "image_url", "image_url": {"url": image_url}},
    ]
    return [{"role": "system", "content": system}] + history[-HISTORY_LEN:] + [
        {"role": "user", "content": content}
    ]


SUMMARY_SYSTEM = """Ты ведёшь досье на собеседника Киви. По старому досье и свежей истории диалога
составь обновлённое короткое досье: кто человек, факты о нём, чем интересен, как обращается к Киви,
тон общения. 3–6 пунктов, только устойчивые факты о собеседнике — без пересказа отдельных реплик.
Пиши по-русски, сжато, без воды."""


def summary_messages(old_summary: str | None, history: list) -> list:
    """Сообщения для LLM-вызова, который обновляет досье: старое досье + недавние ходы."""
    parts = []
    if old_summary:
        parts.append("Старое досье:\n" + old_summary)
    convo = "\n".join(f"{m['role']}: {m['content']}" for m in history)
    parts.append("Свежая история:\n" + convo)
    return [
        {"role": "system", "content": SUMMARY_SYSTEM},
        {"role": "user", "content": "\n\n".join(parts)},
    ]
